"""Guard-level (Tier-B) conformance enumeration for the three case studies.

For every mode, guard valuation and input event, compare the next mode the
Java controller takes against the set of targets the extracted Isabelle model
admits. A row agrees when the admitted target set is exactly {java_next}
({mode} when nothing is enabled).

Two arms, identical except for how the triggering event is read from the theory:
  prefix  theories from the extractor used for Table 4 (reference-runs/)
  fixed   theories regenerated by the current extractor from the same Java

Usage (from the repository root):
  python experiments/conformance-tierB/run_tierb.py prefix
  python experiments/conformance-tierB/run_tierb.py fixed  --thy-root <dir>

For the fixed arm, generate the theories first (one directory per study), e.g.
  scripts/generate_isabelle.sh <dir>
Writes tierb_<arm>_rows.csv and prints per-study agreement.
"""
import argparse, csv, glob, itertools, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import tierb_harness_gen as lib
import tierb_studies as cfgs

REPO = os.path.abspath(os.path.join(HERE, "..", ".."))

def java_next(cfg, jmodes, mode, g, ev):
    if cfg["java_kind"] == "lre":
        return lib.lre_java_next(jmodes, mode, g, ev, cfgs.LRE_PREDS)
    if cfg["java_kind"] == "sranger":
        return lib.sr_java_next(mode, g, ev)
    return lib.cd_java_next(mode, g, ev)

def enumerate_arm(arm, thy_root, java_root):
    rows, unknown_all = [], {}
    for study, cfg in cfgs.STUDIES.items():
        hits = glob.glob(os.path.join(thy_root, study, "**", cfg["thy"]), recursive=True)
        if not hits:
            sys.exit(f"no {cfg['thy']} under {os.path.join(thy_root, study)}")
        ops, listens = lib.parse_thy(hits[0])
        jp = os.path.join(java_root, study, cfg["java_rel"])
        jmodes = lib.lre_java_chains(jp) if cfg["java_kind"] == "lre" else None
        unknown, gnames = set(), list(cfg["gvars"])
        for mode in cfg["modes"]:
            for vals in itertools.product(*[cfg["gvars"][k] for k in gnames]):
                g = dict(zip(gnames, vals))
                for ev in cfg["events"]:
                    jn = java_next(cfg, jmodes, mode, g, ev)
                    adm = lib.model_admits(ops, listens, mode, g, cfg["ev_thy"][ev], cfg, arm, unknown)
                    tg = sorted({o["target"] for o in adm}) or [mode]
                    r = dict(study=study, arm=arm, mode=mode, event=ev)
                    r.update(g)
                    r.update(java_next=jn, model_admits="|".join(tg), n_adm=len(adm),
                             model_ops="|".join(o["name"] for o in adm) or "-", agree=(tg == [jn]))
                    rows.append(r)
        unknown_all[study] = sorted(unknown)
    return rows, unknown_all

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("arm", choices=["prefix", "fixed"])
    ap.add_argument("--thy-root", default=os.path.join(REPO, "reference-runs"))
    ap.add_argument("--java-root", default=os.path.join(REPO, "reference-runs"))
    ap.add_argument("--out", default=None)
    a = ap.parse_args()
    if a.arm == "fixed" and os.path.abspath(a.thy_root) == os.path.join(REPO, "reference-runs"):
        sys.exit("the fixed arm needs --thy-root pointing at regenerated theories")
    rows, unknown = enumerate_arm(a.arm, a.thy_root, a.java_root)
    out = a.out or f"tierb_{a.arm}_rows.csv"
    cols = []
    for r in rows:                      # first-seen order: deterministic across runs
        cols += [k for k in r if k not in cols]
    with open(out, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols); w.writeheader(); w.writerows(rows)
    for study in cfgs.STUDIES:
        rs = [r for r in rows if r["study"] == study]
        ag = sum(r["agree"] for r in rs)
        print(f"{study:18s} states={len(rs):5d} agree={ag:5d} ({100*ag/len(rs):.1f}%)"
              + (f"  unparsed atoms: {unknown[study]}" if unknown[study] else ""))
    print(f"rows written to {out}")

if __name__ == "__main__":
    main()
