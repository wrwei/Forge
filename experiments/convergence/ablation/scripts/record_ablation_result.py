#!/usr/bin/env python3
"""Record the measurement for one compile-only ablation run, and refresh RESULTS.md.

A compile-only ablation run (see ../LAUNCH.md) stops at the first iteration
where all eight VISIBLE phases (compile..isabelle_gen) are green, WITHOUT the
developer ever having read the four behavioural-verifier feedback files. This
script reads the archived iter-*/summary.json for the run, confirms the stop
point, extracts the (withheld) verifier outcomes the runner computed there,
and writes ablation_result.json. It then regenerates RESULTS.md over all runs.

Usage:
    python record_ablation_result.py <study> <run-number> [--root <dir>] [--note "..."]

It does NOT run the pipeline and does NOT read Java; it only reads summary.json.
"""
import argparse, glob, json, os, sys

VISIBLE = ["compile", "coverage", "preflight",
           "t2m", "m2m", "m2t", "dafny_gen", "isabelle_gen"]
BEHAV   = ["fdr4", "dafny_verify", "isabelle_verify", "vacuity"]
STUDIES = ["sranger", "lre", "chemical_detector"]

# Full-loop baseline (iterations to 12/12) for the paper's presented run set.
FULL_LOOP_MEDIAN = {"sranger": 2, "lre": 2, "chemical_detector": 2}

HERE = os.path.dirname(os.path.abspath(__file__))
ABLATION_ROOT = os.path.dirname(HERE)


def load_iters(run_dir):
    its = []
    for d in sorted(glob.glob(os.path.join(run_dir, "iter-*")),
                    key=lambda p: int(p.rsplit("-", 1)[1])):
        sj = os.path.join(d, "summary.json")
        if os.path.exists(sj):
            its.append(json.load(open(sj, encoding="utf-8")))
    return its


def record(study, run, root, note):
    run_dir = os.path.join(root, study, f"run-{run}")
    its = load_iters(run_dir)
    if not its:
        sys.exit(f"no iter-*/summary.json under {run_dir}")
    stop = its[-1]
    pr = stop["phase_results"]

    visible_fail = [p for p in VISIBLE if pr.get(p) == "failed"]
    if visible_fail:
        print(f"WARNING: stop iteration still has FAILED visible phases "
              f"{visible_fail} — the loop should not have stopped here.",
              file=sys.stderr)

    verifiers = {p: pr.get(p, "absent") for p in BEHAV}
    ships_broken = any(v == "failed" for v in verifiers.values())

    result = {
        "study": study,
        "run": run,
        "condition": "compile-only-ablation",
        "compile_only_iters": len(its),
        "stop_phase_results": pr,
        "visible_all_green": not visible_fail,
        "verifiers_at_stop": verifiers,
        "ships_broken": ships_broken,
        "full_loop_baseline_median_iters": FULL_LOOP_MEDIAN.get(study),
        "note": note or "",
    }
    out = os.path.join(run_dir, "ablation_result.json")
    json.dump(result, open(out, "w", encoding="utf-8"), indent=2)
    print(f"wrote {out}")
    print(json.dumps({k: result[k] for k in
                      ("compile_only_iters", "verifiers_at_stop", "ships_broken")},
                     indent=2))
    return result


def refresh_results(root):
    rows = []
    for study in STUDIES:
        for f in sorted(glob.glob(os.path.join(root, study, "run-*", "ablation_result.json"))):
            rows.append(json.load(open(f, encoding="utf-8")))
    rows.sort(key=lambda r: (STUDIES.index(r["study"]), r["run"]))

    def cell(v):  # compact pass/fail
        return {"passed": "pass", "failed": "FAIL", "absent": "--"}.get(v, v)

    lines = [
        "# Compile-Only Ablation — Results",
        "",
        "Auto-generated by `scripts/record_ablation_result.py`. One row per run.",
        "`ships_broken` = the artefact a compile-only loop would have stopped at",
        "fails at least one behavioural verifier (i.e. the verifier feedback was",
        "doing necessary work). Full-loop runs all reach 12/12 by definition.",
        "",
        "| Study | Run | Compile-only iters | FDR4 | Dafny | Isabelle | Vacuity | Ships broken? |",
        "|-------|-----|-------------------|------|-------|----------|---------|---------------|",
    ]
    n_done = n_broken = 0
    for r in rows:
        v = r["verifiers_at_stop"]
        n_done += 1
        n_broken += 1 if r["ships_broken"] else 0
        lines.append(
            f"| {r['study']} | {r['run']} | {r['compile_only_iters']} | "
            f"{cell(v.get('fdr4'))} | {cell(v.get('dafny_verify'))} | "
            f"{cell(v.get('isabelle_verify'))} | {cell(v.get('vacuity'))} | "
            f"{'**YES**' if r['ships_broken'] else 'no'} |")
    lines += [
        "",
        f"**Runs recorded:** {n_done} / 15.  "
        f"**Ships verification-failing artefact:** {n_broken} / {n_done}.",
        "",
        "Headline comparison: *fraction of compile-only stop points that are "
        "verification-clean* (this table) vs *1.0* for the full loop. The "
        "complement is the marginal value of the verifier feedback.",
    ]
    out = os.path.join(root, "RESULTS.md")
    open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print(f"refreshed {out}  ({n_done}/15 runs, {n_broken} ship broken)")


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("study", choices=STUDIES)
    ap.add_argument("run", type=int)
    ap.add_argument("--root", default=ABLATION_ROOT,
                    help="ablation root (default: this script's parent dir)")
    ap.add_argument("--note", default="")
    a = ap.parse_args()
    record(a.study, a.run, a.root, a.note)
    refresh_results(a.root)


if __name__ == "__main__":
    main()
