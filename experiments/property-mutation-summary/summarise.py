#!/usr/bin/env python3
"""Assemble the property-mutation results of all four studies from the per-study CSV and JSON
files into one table (summary.csv) and the LaTeX rows the paper uses (table_rows.tex)."""
import csv, re, json, os, collections
E = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def rows_dafny():
    out = []
    for study, d in [("SRanger", "property-mutation-sranger"), ("LRE", "property-mutation-lre")]:
        for r in csv.reader(open(f"{E}/{d}/results_dafny.csv")):
            if r and r[0].startswith("PD"): out.append((study, r[0], r[1]))
    prog = {"PDG": "Chemical Detector", "PDM": "Chemical Detector", "PDB": "Steam Boiler"}
    for r in csv.reader(open(f"{E}/property-mutation-dafny-others/results_dafny.csv")):
        if r and r[0].startswith("PD"): out.append((prog[r[0][:3]], r[0], r[1]))
    return out
def cls_dafny(study, mid):
    m = re.match(r"PD[GMB]?(\d)([a-z]?)(\d*)", mid); k, sub = m.group(1), m.group(2)
    if study == "SRanger":
        return {"1": "target", "2": "redundant" if mid == "PD2a" else "atom", "3": "target", "4": "true", "5": "pre"}[k]
    if k == "1": return "target"
    if k == "2": return "atom" if (sub == "f" and mid != "PDG2f1") else "redundant"
    if k == "3": return "tight" if mid in {"PD3b", "PD3e", "PDG3b", "PDG3d", "PDM3c"} else "loose"
    return {"4": "true", "5": "pre"}[k]
def rows_isabelle():
    out = []
    for study, d in [("SRanger", "property-mutation-sranger"), ("LRE", "property-mutation-lre"), ("Chemical Detector", "property-mutation-chemical_detector"), ("Steam Boiler", "property-mutation-steam_boiler")]:
        last = collections.OrderedDict()   # SRanger's file also holds the attribution re-run: last line per id wins
        for r in csv.reader(open(f"{E}/{d}/results_isabelle.csv")):
            if r and "PI" in r[0]: last[r[0]] = r[1]
        out += [(study, m, v) for m, v in last.items()]
    return out
def cls_isa(mid):
    k = re.search(r"PI(\d)([ab]?)", mid); n, s = k.group(1), k.group(2)
    return {"1": "listens-", "2": "listens+", "3": "offer+", "4": "offer-", "5": "init", "6": "req-false" if s == "a" else "req-true", "7": "idle"}[n]
def rows_csp():
    files = {"SRanger": [f"{E}/property-mutation-sranger/results/fdr_tracechecks_T.json"], "LRE": [f"{E}/property-mutation-lre/results/fdr_tracechecks_T.json"],
             "Chemical Detector": [f"{E}/property-mutation-csp-others/results/GasAnalysisController_T.json", f"{E}/property-mutation-csp-others/results/MovementController_T.json"],
             "Steam Boiler": [f"{E}/property-mutation-csp-others/results/SteamBoilerController_T.json"]}
    out = []
    for study, fs in files.items():
        for f in fs:
            raw = open(f).read()
            res = [m.group(2) for m in re.finditer(r'"assertion_string": "(.*?)",\s*"errors".*?"result": (\d)', raw, re.S) if "has trace" in m.group(1)]
            assert len(res) == 6, (f, len(res))
            for i, r in enumerate(res): out.append((study, os.path.basename(f), i + 1, "required" if i < 3 else "excluded", "holds" if r == "1" else "absent"))
    return out
D, I, Cs = rows_dafny(), rows_isabelle(), rows_csp()
with open(f"{E}/property-mutation-summary/summary.csv", "w") as f:
    w = csv.writer(f); w.writerow(["verifier", "study", "id", "class", "verdict"])
    for s, m, v in D: w.writerow(["Dafny", s, m, cls_dafny(s, m), v])
    for s, m, v in I: w.writerow(["Isabelle", s, m, cls_isa(m), v])
    for s, f, i, kind, v in Cs: w.writerow(["CSP", s, f"{f.split('_')[0]}#{i}", kind, v])
DN = {"target": "Target mode replaced or negated", "atom": "Guard atom the code tests dropped", "loose": "Guard threshold loosened",
      "redundant": "Redundant conjunct dropped", "tight": "Guard threshold tightened", "true": "True claim the generator omits added", "pre": "Mode precondition dropped"}
IN = {"listens-": "Event removed from a mode's awaited set", "listens+": "Event added to a mode's awaited set", "offer-": "Offer alternative removed", "init": "Initial state changed",
      "req-false": "False requirement asserted", "idle": "Idle operations removed from the machine", "offer+": "Offer alternative no transition handles added", "req-true": "True requirement asserted"}
def table(rows, cls, names):
    T = collections.OrderedDict((k, [0, 0, 0]) for k in names)
    for s, m, v in rows: c = cls(s, m) if cls.__code__.co_argcount == 2 else cls(m); T[c][0] += 1; T[c][1 if v == "FAIL" else 2] += 1
    return T
TD = table(D, cls_dafny, DN); TI = table(I, cls_isa, IN)
L = []
L.append("% generated by experiments/property-mutation-summary/summarise.py; do not edit by hand")
L.append("\\multicolumn{4}{l}{\\emph{Dafny contracts (5 programs, 4 studies)}}\\\\")
for k, (n, f, p) in TD.items(): L.append(f"\\quad {DN[k]} & {n} & {f} & {p}\\\\")
L.append(f"\\quad Total & {sum(v[0] for v in TD.values())} & {sum(v[1] for v in TD.values())} & {sum(v[2] for v in TD.values())}\\\\")
L.append("\\addlinespace\\multicolumn{4}{l}{\\emph{Isabelle theories (5 theories, 4 studies)}}\\\\")
for k, (n, f, p) in TI.items(): L.append(f"\\quad {IN[k]} & {n} & {f} & {p}\\\\")
L.append(f"\\quad Total & {sum(v[0] for v in TI.values())} & {sum(v[1] for v in TI.values())} & {sum(v[2] for v in TI.values())}\\\\")
req = [r for r in Cs if r[3] == "required"]; exc = [r for r in Cs if r[3] == "excluded"]
L.append("\\addlinespace\\multicolumn{4}{l}{\\emph{CSP trace claims (5 controllers, 4 studies)}}\\\\")
L.append(f"\\quad Behaviour the requirements call for & {len(req)} & {sum(r[4]=='absent' for r in req)} & {sum(r[4]=='holds' for r in req)}\\\\")
L.append(f"\\quad Behaviour the requirements exclude & {len(exc)} & {sum(r[4]=='absent' for r in exc)} & {sum(r[4]=='holds' for r in exc)}\\\\")
open(f"{E}/property-mutation-summary/table_rows.tex", "w").write("\n".join(L) + "\n")
print(json.dumps({"dafny": {k: v for k, v in TD.items()}, "isabelle": {k: v for k, v in TI.items()}, "csp_required_holds": sum(r[4]=='holds' for r in req), "csp_excluded_absent": sum(r[4]=='absent' for r in exc), "per_study": {s: [sum(1 for x in D if x[0]==s), sum(1 for x in I if x[0]==s)] for s in ["SRanger","LRE","Chemical Detector","Steam Boiler"]}}))
