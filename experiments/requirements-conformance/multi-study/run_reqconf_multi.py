# ---------------- guard-expression evaluation (mutation-robust) ----------------
# parse_thy splits preconditions on \<and> naively, which fragments a
# parenthesized conjunction inside \<not>(...). Re-join fragments until parens
# balance, then evaluate the full expression over per-arm base semantics.
AND = ' \\<and> '

def rejoin_atoms(atoms):
    out, buf = [], ""
    for a in atoms:
        buf = (buf + AND + a) if buf else a
        if buf.count("(") == buf.count(")"):
            out.append(buf); buf = ""
    if buf: out.append(buf)  # still unbalanced: surface as-is (will be unknown)
    return out

NUM = r"[0-9]+(?:\.[0-9]+)?"
class Foreign(Exception):
    pass

def base_sem(arm):
    """Return fn(atom_string, g) -> bool, raising Foreign for a same-variable
    comparison whose numeric bound differs from the requirement's, KeyError for
    anything unrecognised."""
    def cmp_bool(v_true, comparator, strict_pair):
        # map {>=,>} -> v_true ; {<,<=} -> not v_true (boundary-equal at the
        # abstraction's granularity; recorded in the ambiguity log)
        return v_true if comparator in strict_pair else (not v_true)
    def f(a, g):
        a = a.strip()
        if arm == "sranger":
            m = re.fullmatch(r"distance\(\)\s*(\\<le>|\\<ge>|<|>)\s*obstaclethreshold\(\)", a)
            if m: return cmp_bool(g["obstacleDetected"], m.group(1), ("\\<le>", "<"))
            if a == "turnDurationElapsed": return g["turnDurationElapsed"]
        if arm == "cd_ga":
            if re.fullmatch(r"sts\s*=\s*\(noGas\)", a): return not g["stsIsGasD"]
            if re.fullmatch(r"sts\s*=\s*\(gasD\)", a): return g["stsIsGasD"]
            m = re.fullmatch(r"insVal\s*(\\<le>|\\<ge>|<|>)\s*(" + NUM + ")", a)
            if m:
                if float(m.group(2)) != 10.0: raise Foreign(f"insVal bound {m.group(2)} != requirement threshold 10.0")
                return cmp_bool(g["insAboveThr"], m.group(1), ("\\<ge>", ">"))
        if arm == "cd_mv":
            m = re.fullmatch(r"since\(clockResetTime\(\)\)\s*(\\<le>|\\<ge>|<|>)\s*stuckperiod\(\)", a)
            if m: return cmp_bool(g["elapsedBelowStuckPeriod"], m.group(1), ("<", "\\<le>"))
            m = re.fullmatch(r"\(d1 - d0\)\s*(\\<le>|\\<ge>|<|>)\s*stuckdist\(\)", a)
            if m: return cmp_bool(g["advancedAboveStuckDist"], m.group(1), (">", "\\<ge>"))
        raise KeyError(a)
    return f

def _strip_outer(s):
    s = s.strip()
    while s.startswith("(") and s.endswith(")"):
        depth = 0
        for i, ch in enumerate(s):
            if ch == "(": depth += 1
            elif ch == ")":
                depth -= 1
                if depth == 0 and i < len(s) - 1:
                    return s  # outer parens do not wrap the whole string
        s = s[1:-1].strip()
    return s

def _split_top(s, sep):
    parts, depth, last = [], 0, 0
    i = 0
    while i < len(s):
        if s[i] == "(": depth += 1
        elif s[i] == ")": depth -= 1
        elif depth == 0 and s.startswith(sep, i):
            parts.append(s[last:i]); last = i + len(sep); i = last; continue
        i += 1
    parts.append(s[last:])
    return parts

def eval_expr(s, g, base, unknown, foreign):
    """Evaluate a precondition conjunct: base atoms, \<not>, \<and>, \<or>, parens.
    Returns bool, or None when a sub-expression is unknown/foreign (recorded)."""
    s = " ".join(s.split())
    try:
        return base(s, g)
    except Foreign as e:
        foreign.add(str(e)); return None
    except KeyError:
        pass
    t = _strip_outer(s)
    if t != s:
        return eval_expr(t, g, base, unknown, foreign)
    if t.startswith("\\<not>"):
        v = eval_expr(t[len("\\<not>"):], g, base, unknown, foreign)
        return None if v is None else (not v)
    for sep, op in (("\\<or>", any), ("\\<and>", all)):
        ps = _split_top(t, sep)
        if len(ps) > 1:
            vs = [eval_expr(p, g, base, unknown, foreign) for p in ps]
            if any(v is None for v in vs): return None
            return op(vs)
    unknown.add(t)
    return None

def model_admits2(arm, ops, listens, mode, g, ev_thy, unknown, foreign):
    base = base_sem(arm)
    out = []
    for op in ops:
        if op["state"] != mode: continue
        ok = True
        for a in rejoin_atoms(op["atoms"]):
            v = eval_expr(a, g, base, unknown, foreign)
            if v is None: continue   # unknown/foreign: recorded, non-blocking
            if not v: ok = False; break
        if not ok: continue
        lset = listens.get(mode, set())
        offered = {ev_thy} if (ev_thy is not None and ev_thy in lset) else set()
        if any(e not in offered for e in op["presence"]): continue
        if any(e in offered for e in op["absence"]): continue
        out.append(op)
    return out


def gvar_items(cfg):
    gv = cfg['gvars']
    return list(gv.items()) if hasattr(gv, 'items') else list(gv)

def rel_guard(conjs, g, evals):
    for c in conjs:
        neg = c.startswith('!')
        name = c[1:] if neg else c
        v = evals[name](g)
        if neg: v = not v
        if not v: return False
    return True

def consistent(arm, mode, g, ev):
    if arm == "sranger" and ev == "obstacle" and not g["obstacleDetected"]:
        return False
    return True

def admitted(rel, arm, mode, g, ev, evals):
    enabled, extra = [], set()
    for t in rel["transitions"]:
        if t["kind"] == "initial" or t["source_mode"] != mode: continue
        if t["kind"] == "terminal":
            # a logged decision may admit an equivalent encoding of 'stays'
            # (e.g. MV-A1: the silent step into the terminal sink)
            extra |= set(t.get("also_admits", []))
            continue
        trig = t["trigger_event_or_none"]
        if trig is not None and trig != ev: continue
        if not rel_guard(t["guard_conjuncts"], g, evals): continue
        enabled.append(t)
    if enabled:
        return {t["target_mode"] for t in enabled}, True
    return {mode} | extra, False

def enumerate_arm(arm, thy_path, here):
    relf, cfg, thyname, evals = ARMS[arm]
    rel = json.load(open(os.path.join(here, relf)))
    ops, listens = lib.parse_thy(thy_path)
    unknown, foreign = set(), set()
    rows = []
    for mode in cfg['modes']:
        for vals in itertools.product(*[v for _, v in gvar_items(cfg)]):
            g = dict(zip([k for k, _ in gvar_items(cfg)], vals))
            for ev in cfg['events']:
                R, required = admitted(rel, arm, mode, g, ev, evals)
                en = model_admits2(arm, ops, listens, mode, g, cfg['ev_thy'][ev], unknown, foreign)
                M = {op['target'] for op in en} or {mode}
                if M <= R: verdict = "member"
                elif M == {mode} and required: verdict = "REQ_transition_CODE_none"
                else: verdict = "CODE_transition_REQ_none"
                rows.append(dict(controller=arm, mode=mode, event=ev,
                                 **{k: g[k] for k, _ in gvar_items(cfg)},
                                 flags_consistent=consistent(arm, mode, g, ev),
                                 R_set="|".join(sorted(R)), M_set="|".join(sorted(M)),
                                 required=required, verdict=verdict))
    return rows, unknown, foreign

