#!/usr/bin/env python3
"""thy_term_check.py — static sanity checker for generated Z-Machines theories.

Steam Boiler run: contribution back to the pipeline (finding 5 follow-up).
Parses a *_Beh.thy generated by thy_generation_rule.egl and checks every
zoperation `pre`/`update` quoted string for:

  1. balanced parentheses / brackets;
  2. no Isabelle inner-syntax comments `(*..*)` inside the quoted term (finding 3);
  3. no bare applications of unit-typed auto-consts to a non-unit argument,
     and no application of a declared function to an argument whose inferred
     type disagrees (finding 5): every `f(x)` is checked against the `consts`
     declarations and the zstore lens types;
  4. every identifier referenced is declared somewhere: zstore lens, consts,
     enumtype literal, record field accessor, or Z-Machines builtin.

Usage: python3 thy_term_check.py <theory.thy>
Exit 0 = clean; exit 1 = findings printed one per line.
"""
import re
import sys
from pathlib import Path

BUILTINS = {
    "tr", "st", "listens", "offered", "initial", "Event", "State", "insert",
    "True", "False", "Some", "None", "hd", "tl", "set", "card",
}

def parse_decls(text):
    lenses, consts, enums = {}, {}, set()
    m = re.search(r"^zstore \w+ =(.*?)^  where inv:", text, re.S | re.M)
    if m:
        for name, ty in re.findall(r'^\s+(\w+)\s*::\s*"([^"]+)"', m.group(1), re.M):
            lenses[name] = ty.strip()
    for name, dom, cod in re.findall(
            r'^consts (\w+)\s*::\s*"\s*([^"\\]+?)\s*\\<Rightarrow>\s*([^"]+?)\s*"', text, re.M):
        consts[name] = (dom.strip(), cod.strip())
    for line in re.findall(r"^enumtype \w+ = (.+)$", text, re.M):
        enums.update(x.strip() for x in line.split("|"))
    records = re.findall(r"^record (\w+) = (.+)$", text, re.M)
    fields = set()
    for _, body in records:
        fields.update(re.findall(r"(\w+)\s*::", body))
    return lenses, consts, enums, fields

def term_strings(text):
    """Yield (opname, kind, string) for every pre/update quoted string."""
    for m in re.finditer(
            r"zoperation (\w+) =.*?pre \"(.*?)\"\s*(?:update \"(.*?)\")?\s*(?:\$|\n\s*\n)",
            text, re.S):
        yield m.group(1), "pre", m.group(2)
        if m.group(3):
            yield m.group(1), "update", m.group(3)

SYMBOL = re.compile(r"\\<\w+>")   # Isabelle markup: \<and>, \<Zprime>, ...

def check(path):
    text = Path(path).read_text()
    lenses, consts, enums, fields = parse_decls(text)
    problems = []
    n = 0
    for op, kind, s in term_strings(text):
        n += 1
        s = SYMBOL.sub(" ", s)   # strip markup so tokens like 'and'/'Zprime' don't surface
        # 1. balance
        for o, c in [("(", ")"), ("[", "]"), ("{", "}")]:
            if s.count(o) != s.count(c):
                problems.append(f"{op}/{kind}: unbalanced {o}{c} ({s.count(o)} vs {s.count(c)})")
        # 2. inner-syntax comments
        if "(*" in s:
            problems.append(f"{op}/{kind}: inner-syntax comment '(*' inside quoted term")
        # 3. applications f(arg): unit-typed consts applied to non-unit
        for fn, arg in re.findall(r"(\w+)\(([^()]{1,60})\)", s):
            arg = arg.strip()
            if fn in consts:
                dom, _ = consts[fn]
                if dom == "unit" and arg:
                    problems.append(
                        f"{op}/{kind}: unit-typed const '{fn}' applied to '{arg}'")
                if dom in ("real", "int", "nat") and arg:
                    aty = infer(arg, lenses, consts)
                    if aty and aty != dom and not (dom == "real" and aty in ("real",)):
                        problems.append(
                            f"{op}/{kind}: '{fn}' expects {dom}, got '{arg}' :: {aty}")
        # 4. undeclared identifiers (word tokens not numbers/operators)
        for tok in set(re.findall(r"[A-Za-z_]\w*", s)):
            if tok in BUILTINS or tok in enums or tok in fields:
                continue
            if tok in lenses or tok in consts:
                continue
            if tok.endswith("_input") or tok.startswith("NID_"):
                continue
            if re.fullmatch(r"[A-Z][A-Z0-9_]*", tok):   # state / enum constructors
                continue
            problems.append(f"{op}/{kind}: undeclared identifier '{tok}'")
    return n, problems

def infer(arg, lenses, consts):
    arg = arg.strip()
    if re.fullmatch(r"\d+", arg):
        return "int"
    if re.fullmatch(r"\d+\.\d+", arg):
        return "real"
    m = re.fullmatch(r"(\w+)(\(\))?", arg)
    if m:
        name = m.group(1)
        if name in lenses:
            return lenses[name]
        if name in consts:
            return consts[name][1]
    return None  # compound expression - skip (conservative)

if __name__ == "__main__":
    if len(sys.argv) != 2:
        print(__doc__); sys.exit(2)
    n, problems = check(sys.argv[1])
    print(f"checked {n} pre/update strings")
    for p in sorted(set(problems)):
        print("FINDING:", p)
    sys.exit(1 if problems else 0)
